#!/usr/bin/env python3
"""Regenerates the photo-field block at the end of hrzest-before-crs.conf.

    python3 scripts/host-hardening/modsecurity/gen_photo_exclusions.py

libmodsecurity 3.0.12 (Ubuntu 24.04) takes no regular expressions as ctl:
targets, so each (rule, field) pair is listed. Edit FIELDS / FRAMES / RULES
here, not the generated block. tests/test_firewall_host_configs.py checks
that the file matches what this prints.
"""
import pathlib

# CRS rules that read the "data:image/jpeg;base64," prefix as an attack.
RULES = ("932235", "932260", "934170", "941130", "941170")
# Fields that carry a photo as a data: URI, form-encoded or JSON.
FIELDS = ("face_image", "face_photo", "photo")
# Liveness frames the app reads (utils/liveness.py MAX_FRAMES).
FRAMES = 16
FIRST_ID = 1001040
MARKER = "# ── photos sent as data: URIs"

HEADER = """# ── photos sent as data: URIs ───────────────────────────────────────────────
# Check-in and profile photos arrive as "data:image/jpeg;base64,...". The
# prefix alone reads as an XSS attribute vector (941130, 941170), a PHP data
# scheme (934170) and a ";" command separator (932235, 932260) -- 25 points,
# every time. Excluded for these fields only (and the liveness frames the app
# reads), never by value: a value-based exclusion would let a request switch
# the rules off for its other fields by carrying one dummy image. The app
# decodes these as base64 and rejects anything else.
# Generated by gen_photo_exclusions.py -- edit that, not this block.
"""


def block():
    targets = [f"ARGS:{f}" for f in FIELDS] + [f"ARGS:json.{f}" for f in FIELDS]
    frames = [f"ARGS:json.liveness.frames.array_{i}" for i in range(FRAMES)]
    out, rid = [HEADER.rstrip("\n")], FIRST_ID
    for group in (targets, frames):
        for rule in RULES:
            lines = ['SecAction \\', f'    "id:{rid},phase:1,pass,nolog,\\']
            ctls = [f"    ctl:ruleRemoveTargetById={rule};{t}" for t in group]
            lines += [c + ",\\" for c in ctls[:-1]] + [ctls[-1] + '"']
            out.append("\n".join(lines))
            rid += 1
    return "\n".join(out) + "\n"


def render(existing):
    head = existing.split(MARKER, 1)[0].rstrip("\n")
    return head + "\n\n" + block()


if __name__ == "__main__":
    path = pathlib.Path(__file__).with_name("hrzest-before-crs.conf")
    text = path.read_bytes().decode().replace("\r\n", "\n")
    path.write_bytes(render(text).encode())
    print(f"wrote {path}")
